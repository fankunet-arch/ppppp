<?php
declare(strict_types=1);

use Vip\BusinessDay;

T::group('BusinessDay —— 切点 02:00，跨零点归前一营业日');

$bd = new BusinessDay('02:00');

T::eq('2024-01-26', $bd->of('2024-01-26 21:44:54'),
    '晚市 21:44 结账 → 归 1/26');
T::eq('2024-01-26', $bd->of('2024-01-27 00:01:43'),
    '★ 00:01 结账 → 归【1/26】。serial_id 是 2401270001（结账自然日），不可直接当营业日');
T::eq('2024-01-26', $bd->of('2024-01-27 01:59:59'),
    '01:59 结账仍归 1/26');
T::eq('2024-01-27', $bd->of('2024-01-27 02:00:00'),
    '02:00 整点起归当日');
T::eq('2026-08-13', $bd->of('2026-08-13 16:00:00'),
    '午市 16:00（实测峰值时段）归当日');
T::eq('2026-08-13', $bd->of('2026-08-13 23:26:08'),
    '晚市 23:26（实测最后一单）归当日');

T::group('BusinessDay —— 营业日 → 时间区间');

T::eq(['2026-08-13 02:00:00', '2026-08-14 02:00:00'], $bd->range('2026-08-13'),
    '营业日 8/13 = [8/13 02:00, 8/14 02:00)');

T::group('BusinessDay —— 切点可配（02:00/04:00/06:00 实测等价）');

$bd4 = new BusinessDay('04:00');
T::eq('2024-01-26', $bd4->of('2024-01-27 01:59:59'),
    '切点 04:00 下 01:59 仍归前一日（该区间实测 0 单，结果与 02:00 一致）');
T::eq('2024-01-27', $bd4->of('2024-01-27 04:00:00'),
    '切点 04:00 下 04:00 起归当日');
