<?php
declare(strict_types=1);

use Vip\Money;

T::group('Money —— 金额以整数分流转，避免浮点误差');

T::eq(5830, Money::toCents('58.30'),  '"58.30" → 5830 分');
T::eq(2390, Money::toCents('23.90'),  '"23.90" → 2390 分');
T::eq(7170, Money::toCents('71.70'),  '"71.70" → 7170 分（3 份套餐的行小计）');
T::eq(0,    Money::toCents('0.00'),   '"0.00" → 0');
T::eq(0,    Money::toCents(null),     'NULL → 0');
T::eq(-1088, Money::toCents('-10.88'), '负数折扣 "-10.88" → -1088');
T::eq(2, Money::toCents('0.02'), '"0.02" → 2 分（分币舍入场景）');

// 浮点陷阱：(int)(0.29 * 100) 在 IEEE754 下是 28
T::eq(29, Money::toCents('0.29'), '"0.29" → 29 分（浮点直转会得 28）');
T::eq(1170, Money::toCents('11.70'), '"11.70" → 1170 分');

T::eq('58.30', Money::toStr(5830), '5830 分 → "58.30"');
T::eq('0.00',  Money::toStr(0),    '0 → "0.00"');
T::eq('-10.88', Money::toStr(-1088), '-1088 → "-10.88"');
T::eq('1234.05', Money::toStr(123405), '123405 → "1234.05"');

T::group('Money::scale —— 按比例缩放（不计分项的扣除）');

// 订单 114.10，其中 14.10 不计分 → 保留 100.00/114.10
T::eq(10000, Money::scale(11410, 10000, 11410), '11410 × (10000/11410) = 10000');
T::eq(5000,  Money::scale(10000, 1, 2),          '10000 的一半 = 5000');
T::eq(3333,  Money::scale(10000, 1, 3),          '10000 的三分之一 = 3333（四舍五入）');
T::eq(6667,  Money::scale(10000, 2, 3),          '10000 的三分之二 = 6667');
T::eq(0,     Money::scale(10000, 0, 11410),      '全部扣除 → 0');

T::group('Money::splitEvenly —— AA 均摊，余数给第一位，分毫不差');

$s = Money::splitEvenly(10000, 3);
T::eq([3334, 3333, 3333], $s, '100.00 分 3 份 → 33.34 / 33.33 / 33.33');
T::eq(10000, array_sum($s), '合计仍是 100.00，不丢分');

$s2 = Money::splitEvenly(5830, 2);
T::eq([2915, 2915], $s2, '58.30 分 2 份 → 29.15 / 29.15');
T::eq(5830, array_sum($s2), '合计不变');

$s3 = Money::splitEvenly(101, 4);
T::eq([26, 25, 25, 25], $s3, '1.01 分 4 份 → 余数 1 分给第一位');
T::eq(101, array_sum($s3), '合计不变');

T::eq([], Money::splitEvenly(100, 0), 'n=0 返回空数组，不除零');
