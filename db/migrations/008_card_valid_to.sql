-- ============================================================
-- 008 · 卡片有效期
--
-- 为什么是「固定日期印在卡上」而不是「N 个月不活跃就清零」：
--
-- 客人查不到任何东西 —— 没有线上入口，手里只有一张卡。
-- 「24 个月没消费就清零」这种规则，客人无从判断自己处在什么位置，
-- 一旦投诉，店家拿不出「已经告知」的证据（除非发卡时签字或建公网系统，
-- 两者都不现实）。
--
-- 而固定日期印在卡面上，【卡片本身就是告知的证据】：事前、明确、显著，
-- RDL 1/2007 判断不公平条款的三个要件一次满足。
--
-- 缺陷是常客也会被清零 —— 补法是「有效期属于卡片，不属于积分」：
-- 到期前到店可换发新卡，积分、计次、未兑换的券全部结转（复用挂失换卡那条
-- 链路）。于是效果上等同于不活跃期，而告知责任由卡面承担。
-- 实际给的比卡面承诺的宽松，这在合规上永远只有好处。
--
-- 有效期按【批次】设：印刷是按批的，同一批同一个日期，天然吻合。
--
-- ★ 兼容性同 001_init.sql，见 db/README.md
-- ============================================================

SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

ALTER TABLE `card`
  ADD COLUMN `valid_to` DATE DEFAULT NULL
      COMMENT '有效期至（含当天）。必须与卡面印刷的日期一致；NULL = 不设有效期'
      AFTER `batch_no`,
  ADD COLUMN `points_cleared_at` DATETIME DEFAULT NULL
      COMMENT '过期宽限结束后清零积分的时间；留痕供客人申诉时查'
      AFTER `voided_at`;

-- 按有效期扫的夜间任务要走索引
ALTER TABLE `card`
  ADD KEY `idx_valid` (`store_code`,`valid_to`);
